let selectedLanguage =
  localStorage.getItem("maharaLanguage") === "ar"
    ? "ar"
    : "en";


/* =========================================================
   TRANSLATION FUNCTION
   ========================================================= */

function applyTranslation(language) {

  if (!translations[language]) {
    language = "en";
  }

  selectedLanguage =
    language;

  const current =
    translations[selectedLanguage];


  /* HTML */

  document.documentElement.lang =
    selectedLanguage;

  document.documentElement.dir =
    selectedLanguage === "ar"
      ? "rtl"
      : "ltr";

  document.documentElement.dataset.language =
    selectedLanguage;


  /* Text */

  document
    .querySelectorAll("[data-i18n]")
    .forEach((element) => {

      const key =
        element.dataset.i18n;

      if (
        Object.prototype.hasOwnProperty.call(
          current,
          key
        )
      ) {

        element.textContent =
          current[key];

      }

    });


  /* HTML */

  document
    .querySelectorAll("[data-i18n-html]")
    .forEach((element) => {

      const key =
        element.dataset.i18nHtml;

      if (
        Object.prototype.hasOwnProperty.call(
          current,
          key
        )
      ) {

        element.innerHTML =
          current[key];

      }

    });


  /* Placeholders */

  document
    .querySelectorAll("[data-i18n-placeholder]")
    .forEach((element) => {

      const key =
        element.dataset.i18nPlaceholder;

      if (
        Object.prototype.hasOwnProperty.call(
          current,
          key
        )
      ) {

        element.placeholder =
          current[key];

      }

    });


  /* Language buttons */

  document
    .querySelectorAll(".lang-option")
    .forEach((button) => {

      const active =
        button.dataset.lang ===
        selectedLanguage;

      button.classList.toggle(
        "active",
        active
      );

      button.setAttribute(
        "aria-pressed",
        String(active)
      );

    });


  /* WhatsApp */

  const whatsapp =
    document.querySelector(
      ".floating-whatsapp"
    );

  if (whatsapp) {

    whatsapp.setAttribute(
      "aria-label",
      current["aria.whatsapp"]
    );

    whatsapp.setAttribute(
      "data-tooltip",
      selectedLanguage === "ar"
        ? "تواصل معنا عبر واتساب"
        : "Chat with us"
    );

  }


  /* Save */

  localStorage.setItem(
    "maharaLanguage",
    selectedLanguage
  );


  updateAccessibility();

}


/* =========================================================
   ACCESSIBILITY
   ========================================================= */

function updateAccessibility() {

  const toggle =
    document.querySelector(
      ".nav-toggle"
    );

  if (!toggle) return;

  toggle.setAttribute(
    "aria-label",
    selectedLanguage === "ar"
      ? "فتح قائمة التنقل"
      : "Open navigation"
  );

}


/* =========================================================
   MOBILE MENU
   ========================================================= */

function closeMobileMenu() {

  const menu =
    document.getElementById(
      "navMenu"
    );

  const toggle =
    document.querySelector(
      ".nav-toggle"
    );

  if (!menu) return;

  menu.classList.remove(
    "open"
  );

  if (toggle) {

    toggle.setAttribute(
      "aria-expanded",
      "false"
    );

  }

}


