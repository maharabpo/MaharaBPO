/* =========================================================
   DOM READY
   ========================================================= */

document.addEventListener(
  "DOMContentLoaded",
  () => {

    const navToggle =
      document.querySelector(".nav-toggle");

    const navMenu =
      document.getElementById("navMenu");

    const navLinks =
      document.querySelectorAll(
        ".nav-menu a"
      );

    const quoteForm =
      document.getElementById("quoteForm");

    const whatsappQuoteBtn =
      document.getElementById(
        "whatsappQuoteBtn"
      );


    /* -----------------------------------------
       INITIAL LANGUAGE
       ----------------------------------------- */

    applyTranslation(
      getStoredLanguage()
    );


    /* -----------------------------------------
       MOBILE NAVIGATION
       ----------------------------------------- */

    if (
      navToggle &&
      navMenu
    ) {

      navToggle.addEventListener(
        "click",
        () => {

          const isOpen =
            navMenu.classList.toggle(
              "open"
            );

          navToggle.setAttribute(
            "aria-expanded",
            String(isOpen)
          );
        }
      );

      navLinks.forEach(
        (link) => {

          link.addEventListener(
            "click",
            () => {
              closeMobileMenu();
            }
          );

        }
      );
    }


    /* -----------------------------------------
       LANGUAGE SWITCHER
       ----------------------------------------- */

    document
      .querySelectorAll(".lang-option")
      .forEach((button) => {

        button.addEventListener(
          "click",
          () => {

            const language =
              button.dataset.lang;

            applyTranslation(
              language
            );

            closeMobileMenu();
          }
        );

      });


    /* -----------------------------------------
       FORM SUBMISSION
       ----------------------------------------- */

    if (quoteForm) {

      quoteForm.addEventListener(
        "submit",
        (event) => {

          event.preventDefault();

          if (
            !validateQuoteForm(
              quoteForm
            )
          ) {

            updateFormMessage(
              "form.message.required"
            );

            const firstError =
              quoteForm.querySelector(
                ".input-error"
              );

            if (firstError) {
              firstError.focus();
            }

            return;
          }

          const data =
            collectQuoteData();

          if (!data) return;

          const subject =
            selectedLanguage === "ar"
              ? "طلب جديد لخدمات مهارة BPO"
              : "New Customer Experience Inquiry - MAHARA BPO";

          const emailBody =
            createEmailBody(data);

          const mailto =
            `mailto:Info@MaharaBPO.com` +
            `?subject=${encodeURIComponent(subject)}` +
            `&body=${encodeURIComponent(emailBody)}`;

          window.location.href =
            mailto;

          updateFormMessage(
            "form.message.email"
          );
        }
      );
    }


    /* -----------------------------------------
       WHATSAPP FORM BUTTON
       ----------------------------------------- */

    if (
      whatsappQuoteBtn &&
      quoteForm
    ) {

      whatsappQuoteBtn.addEventListener(
        "click",
        () => {

          if (
            !validateQuoteForm(
              quoteForm
            )
          ) {

            updateFormMessage(
              "form.message.required"
            );

            const firstError =
              quoteForm.querySelector(
                ".input-error"
              );

            if (firstError) {
              firstError.focus();
            }

            return;
          }

          const data =
            collectQuoteData();

          if (!data) return;

          const message =
            createWhatsAppMessage(
              data
            );

          const whatsappUrl =
            `https://wa.me/923471417357?text=` +
            encodeURIComponent(message);

          window.open(
            whatsappUrl,
            "_blank",
            "noopener,noreferrer"
          );

          updateFormMessage(
            "form.message.whatsapp"
          );
        }
      );
    }


    /* -----------------------------------------
       REMOVE FORM ERROR WHEN USER TYPES
       ----------------------------------------- */

    quoteForm
      ?.querySelectorAll(
        "input, select, textarea"
      )
      .forEach((field) => {

        field.addEventListener(
          "input",
          () => {
            field.classList.remove(
              "input-error"
            );
          }
        );

        field.addEventListener(
          "change",
          () => {
            field.classList.remove(
              "input-error"
            );
          }
        );

      });

  }
);


