/* =========================================================
   CLICK OUTSIDE MOBILE MENU
   ========================================================= */

document.addEventListener(
  "click",
  (event) => {

    const navMenu =
      document.getElementById(
        "navMenu"
      );

    const navToggle =
      document.querySelector(
        ".nav-toggle"
      );

    if (
      !navMenu ||
      !navMenu.classList.contains(
        "open"
      )
    ) {
      return;
    }

    if (
      !navMenu.contains(
        event.target
      ) &&
      !navToggle?.contains(
        event.target
      )
    ) {

      closeMobileMenu();
    }

  }
);


