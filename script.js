/* =========================================================
   VALIDATION
   ========================================================= */

function validateForm(form) {

  let valid =
    true;


  form
    .querySelectorAll("[required]")
    .forEach((field) => {

      field.classList.remove(
        "input-error"
      );

      if (
        !String(field.value || "").trim()
      ) {

        field.classList.add(
          "input-error"
        );

        valid =
          false;

      }

    });


  const email =
    form.querySelector(
      'input[type="email"]'
    );


  if (
    email &&
    email.value.trim() &&
    !/^[^\s@]+@[^\s@]+\.[^\s@]+$/
      .test(email.value.trim())
  ) {

    email.classList.add(
      "input-error"
    );

    valid =
      false;

  }


  return valid;

}


